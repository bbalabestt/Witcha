import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "src/assets/icons");
const files = readdirSync(dir).filter((f) => f.endsWith(".svg")).sort();

const entries = files.map((file) => {
  const svg = readFileSync(path.join(dir, file), "utf8");
  const inner = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1]?.trim();
  if (!inner) throw new Error(`Cannot parse ${file}`);
  if (/#[0-9a-f]{3,6}/i.test(inner)) throw new Error(`${file} has a hard-coded colour; use currentColor`);
  return [file.replace(/\.svg$/, ""), inner];
});

const out = [
  "// Generated by scripts/build-icons.mjs from src/assets/icons. Do not edit.",
  "export const iconMarkup = {",
  ...entries.map(([name, inner]) => `  ${JSON.stringify(name)}: ${JSON.stringify(inner)},`),
  "} as const;",
  "",
  "export type IconName = keyof typeof iconMarkup;",
  "",
];
writeFileSync(path.join(root, "src/components/ui/icons.generated.ts"), out.join("\n"));
console.log(`Wrote ${entries.length} icons`);
